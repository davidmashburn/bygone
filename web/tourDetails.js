import { ChangeTourCheckCategory, ChangeTourCheckStatus } from '../src/tourDetails.ts';
import { TourOptionField, tourOptionLabel } from '../src/tourOptions.ts';
import { renderTourProse } from '../media/tourProse.js';

const checkCategories = [
    [ChangeTourCheckCategory.Provenance, 'Provenance'],
    [ChangeTourCheckCategory.Claims, 'Claims'],
    [ChangeTourCheckCategory.Behavior, 'Behavior'],
    [ChangeTourCheckCategory.Coverage, 'Coverage'],
    [ChangeTourCheckCategory.Uncertainty, 'Uncertainty']
];
const checkStatusLabels = {
    [ChangeTourCheckStatus.Verified]: 'Verified',
    [ChangeTourCheckStatus.Partial]: 'Partial',
    [ChangeTourCheckStatus.NotChecked]: 'Not checked',
    [ChangeTourCheckStatus.NotApplicable]: 'Not applicable'
};

function text(tag, value) {
    const element = document.createElement(tag);
    element.textContent = value === null || value === undefined ? '' : String(value);
    return element;
}

function prose(value) {
    const element = document.createElement('p');
    element.append(...renderTourProse(document, value));
    return element;
}

function renderChecks(checks) {
    const disclosure = document.createElement('details');
    disclosure.className = 'tour-checks';
    disclosure.append(text('summary', 'Checks & evidence'));
    disclosure.append(text('p', 'Author-supplied checks for the scope described below. Missing entries are not checked.'));
    for (const [category, label] of checkCategories) {
        const check = checks?.[category];
        const item = document.createElement('details');
        item.className = 'tour-check-category';
        item.dataset.checkCategory = category;
        const status = check?.status ?? ChangeTourCheckStatus.NotChecked;
        item.append(text('summary', `${label} · ${checkStatusLabels[status]}`));
        item.append(prose(check?.summary ?? 'No check supplied.'));
        if (check?.details) item.append(prose(check.details));
        disclosure.append(item);
    }
    return disclosure;
}

function renderAuthor(author) {
    const section = document.createElement('section');
    section.append(text('h2', 'Human author'));
    const list = document.createElement('dl');
    list.append(text('dt', 'Name'), text('dd', author.name));
    if (author.url) list.append(text('dt', 'URL'), text('dd', author.url));
    section.append(list);
    return section;
}

const optionFields = [
    [TourOptionField.Style, 'Style'],
    [TourOptionField.Depth, 'Depth'],
    [TourOptionField.Audience, 'Audience'],
    [TourOptionField.Familiarity, 'Familiarity'],
    [TourOptionField.Coverage, 'Coverage requested']
];

const optionFieldLabels = new Map(optionFields);
optionFieldLabels.set(TourOptionField.Emphasis, 'Emphasis');

function renderOptionValue(field, value) {
    if (field === TourOptionField.Emphasis && (!value || !value.length)) return 'None';
    if (Array.isArray(value)) {
        return value.map((item) => tourOptionLabel(field, item)).join(', ');
    }
    return tourOptionLabel(field, value);
}

function renderOptions(options) {
    const disclosure = document.createElement('details');
    disclosure.className = 'tour-options';
    disclosure.append(text('summary', 'Resolved options'));
    const list = document.createElement('dl');
    for (const [field, label] of optionFields) {
        if (options[field] !== undefined) {
            list.append(text('dt', label), text('dd', renderOptionValue(field, options[field])));
        }
    }
    if (options.emphasis?.length) {
        list.append(
            text('dt', 'Emphasis'),
            text('dd', renderOptionValue(TourOptionField.Emphasis, options.emphasis))
        );
    }
    list.append(text('dt', 'Scope'), text('dd', options.paths?.length ? options.paths.join(', ') : 'Whole comparison'));
    if (options.inferred?.length) {
        const inferred = options.inferred.map((field) => {
            const value = options[field];
            const label = optionFieldLabels.get(field) ?? field;
            return `${label}: ${renderOptionValue(field, value)}`;
        });
        list.append(text('dt', 'Inferred choices'), text('dd', inferred.join('; ')));
    }
    disclosure.append(list);
    if (options.notes) disclosure.append(text('h3', 'Notes'), prose(options.notes));
    return disclosure;
}

export function renderTourDetails(host, tour) {
    host.replaceChildren();
    host.hidden = !tour;
    if (!tour) return;
    const audience = tour?.details?.audience;
    const generator = tour?.generatedBy;
    host.append(renderChecks(tour.details?.checks));
    if (tour.author) host.append(renderAuthor(tour.author));
    if (generator) {
        host.append(text('h2', 'Generated by'));
        const list = document.createElement('dl');
        for (const [label, value] of [
            ['Provider', generator.provider], ['Model', generator.model], ['Harness', generator.harness], ['Effort', generator.effort]
        ]) {
            if (value) list.append(text('dt', label), text('dd', value));
        }
        host.append(list);
    }
    if (tour.options) host.append(renderOptions(tour.options));
    if (!audience) return;
    host.append(text('h2', 'Audience'));
    host.append(text('p', `${audience.purpose[0].toUpperCase() + audience.purpose.slice(1)}${audience.estimatedMinutes ? ` · about ${audience.estimatedMinutes} min` : ''}`));
    host.append(text('p', audience.scope));
    const detail = document.createElement('details');
    detail.append(text('summary', 'Assumed familiarity'));
    const list = document.createElement('dl');
    for (const [label, value] of [
        ['Codebase', { none: 'New to this codebase', some: 'Some familiarity', maintainer: 'Maintainer' }[audience.codebase]],
        ['Language', { none: 'No prior knowledge', basic: 'Basic', fluent: 'Fluent', advanced: 'Advanced' }[audience.language]],
        ['Reading demand', audience.readingDemand],
        ['Prerequisites', audience.domain?.join('; ') || 'None specified']
    ]) list.append(text('dt', label), text('dd', value));
    detail.append(list);
    host.append(detail);
}
