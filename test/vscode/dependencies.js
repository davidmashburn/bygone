const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const vscode = require('vscode');

exports.run = async () => {
    const root = process.env.BYGONE_FOLLOW_FIXTURE;
    const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
    git('branch', '-M', 'main');
    const base = git('rev-parse', 'HEAD');
    git('checkout', '-b', 'dependency-fixture');
    const source = 'def helper():\n    pass\n\ndef run():\n    helper()\n';
    const file = path.join(root, 'app.py');
    fs.writeFileSync(file, source); git('add', '.'); git('commit', '-m', 'dependency fixture');
    const head = git('rev-parse', 'HEAD');
    const document = await vscode.workspace.openTextDocument(vscode.Uri.file(file));
    await vscode.window.showTextDocument(document);
    const api = await vscode.extensions.getExtension('davidmashburn.bygone').activate();
    await vscode.commands.executeCommand('bygone.openDependencies');
    const controller = api.dependencies;
    assert.ok(controller.report, controller.panel?.webview.html);
    assert.equal(controller.report.range.baseOid, base);
    assert.equal(controller.report.range.headOid, head);
    assert.ok(controller.report.head.nodes.some(n => n.name === 'run'));
    assert.match(controller.panel.webview.html, /Dependency changes and affected consumers/);
    const anchor = controller.report.head.nodes.find(n => n.name === 'run').source;
    await controller.openSource(anchor);
    assert.equal(vscode.window.activeTextEditor.document.uri.scheme, 'bygone-dependency');
    assert.equal(vscode.window.activeTextEditor.document.getText(), source);
    assert.equal(vscode.window.activeTextEditor.document.offsetAt(vscode.window.activeTextEditor.selection.start), anchor.start);
    await assert.rejects(controller.openSource({ ...anchor, digest: '0'.repeat(64) }), /unavailable or changed/);
    console.log('DEPENDENCIES PASS command, Python worker assets, pinned source navigation, digest validation');

    const reviewFile = path.join(root, 'review.json');
    const review = { version: 2, repository: 'fixture', base, head, requirements: [], questions: [], links: [], runs: [], analyses: [], decisions: [] };
    fs.writeFileSync(reviewFile, JSON.stringify(review));
    await vscode.commands.executeCommand('bygone.openEvidenceReview', vscode.Uri.file(reviewFile), vscode.Uri.file(root));
    await api.evidence.action({ action: 'graph' });
    assert.equal(controller.report.range.baseOid, base);
    assert.equal(controller.report.range.headOid, head);
    const pending = controller.open({ repoRoot: root, baseOid: base, headOid: head });
    controller.panel.dispose();
    await pending;
    assert.equal(controller.panel, undefined);
    assert.equal(controller.report, undefined);
    assert.equal(controller.analysis.signal.aborted, true);
    console.log('DEPENDENCIES PASS evidence review endpoints and disposal cancellation');
};
